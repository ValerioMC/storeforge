<script setup lang="ts">
import { computed, reactive, ref } from 'vue'
import AppSelect from '../../../components/ui/AppSelect.vue'
import Modal from '../../../components/ui/Modal.vue'
import Notice from '../../../components/ui/Notice.vue'
import { rgwUserLabel, type RgwAccount, type RgwAccountLimits, type RgwChange, type RgwKind, type RgwUser } from '../model/rgw'
import RgwIdentityPicker from './RgwIdentityPicker.vue'

const props = defineProps<{ connection: string; kind: RgwKind; managed: boolean; account?: RgwAccount; user?: RgwUser; busy: boolean; error: string }>()
const emit = defineEmits<{ close: []; save: [change: RgwChange] }>()
const existing = props.account ?? props.user
const editing = !!existing
const name = ref(props.account?.name ?? props.user?.displayName ?? '')
const email = ref(existing?.email ?? '')
const tenant = ref(props.account?.tenant ?? props.user?.identity.tenant ?? '')
const accountId = ref('')
const uid = ref(props.user?.identity.uid ?? '')
const rootUid = ref('')
const owningAccount = ref<string>()
const root = ref(false)
const state = ref(props.user?.suspended == null ? '' : props.user.suspended ? 'suspended' : 'active')
const limits = reactive<Partial<Record<keyof RgwAccountLimits, number | string>>>({
  maxUsers: props.account?.limits.maxUsers ?? '',
  maxBuckets: props.account?.limits.maxBuckets ?? props.user?.maxBuckets ?? '',
  maxRoles: props.account?.limits.maxRoles ?? '',
  maxGroups: props.account?.limits.maxGroups ?? '',
  maxAccessKeys: props.account?.limits.maxAccessKeys ?? '',
})
const accountFields = [
  { field: 'maxUsers', label: 'Users' }, { field: 'maxBuckets', label: 'Buckets' },
  { field: 'maxRoles', label: 'Roles' }, { field: 'maxGroups', label: 'Groups' },
  { field: 'maxAccessKeys', label: 'Keys per user' },
] as const
const invalid = computed(() => props.busy || !name.value.trim() || (!editing && props.kind === 'user' && !uid.value.trim()) ||
  (!editing && props.kind === 'account' && props.managed && !rootUid.value.trim()))

function limit(field: keyof RgwAccountLimits): number | null {
  const value = limits[field]
  return typeof value === 'number' ? value : null
}

function save(): void {
  if (invalid.value) return
  if (props.kind === 'account') {
    const draft = { name: name.value, email: email.value, limits: {
      maxUsers: limit('maxUsers'), maxBuckets: limit('maxBuckets'), maxRoles: limit('maxRoles'),
      maxGroups: limit('maxGroups'), maxAccessKeys: limit('maxAccessKeys'),
    } }
    if (props.account) emit('save', { action: 'updateAccount', id: props.account.id, draft })
    else emit('save', { action: 'createAccount', id: accountId.value || null, tenant: tenant.value, draft, rootUid: rootUid.value || null, managed: props.managed })
    return
  }
  const draft = { displayName: name.value, email: email.value, suspended: state.value ? state.value === 'suspended' : null, maxBuckets: limit('maxBuckets') }
  if (props.user) emit('save', { action: 'updateUser', identity: props.user.identity, draft })
  else emit('save', { action: 'createUser', identity: { tenant: tenant.value, uid: uid.value }, draft,
    account: owningAccount.value ?? null, root: !!owningAccount.value && root.value, managed: props.managed })
}
</script>

<template>
  <Modal :title="`${editing ? 'Edit' : 'Create'} RGW ${kind}`" @close="!busy && emit('close')">
    <form class="modal-form" @submit.prevent="save">
      <Notice v-if="error" tone="error">{{ error }}</Notice>
      <p v-if="account">{{ account.id }} · {{ account.tenant || 'Default tenant' }}</p>
      <p v-if="user">{{ rgwUserLabel(user.identity) }}{{ user.account ? ` · ${user.account}` : '' }}</p>
      <div class="form-grid">
        <label>{{ kind === 'account' ? 'Account name' : 'Display name' }}<input v-model="name" required :disabled="busy" /></label>
        <label>Email<input v-model="email" type="email" :disabled="busy" /></label>
        <label v-if="!editing">Tenant<input v-model="tenant" :disabled="busy" placeholder="Default tenant" /></label>
        <label v-if="!editing && kind === 'user'">UID<input v-model="uid" required :disabled="busy" spellcheck="false" /></label>
        <label v-if="!editing && kind === 'account'">Account ID<input v-model="accountId" :disabled="busy" placeholder="Generated by gateway" spellcheck="false" /></label>
        <label v-if="!editing && kind === 'account'">Root UID<input v-model="rootUid" :required="managed" :disabled="busy" spellcheck="false" /></label>
        <label v-if="kind === 'user'">User state
          <AppSelect v-model="state" :options="[{ value: '', label: 'Provider default' }, { value: 'active', label: 'Active' }, { value: 'suspended', label: 'Suspended' }]" :disabled="busy" />
        </label>
        <label v-for="{ field, label } in kind === 'account' ? accountFields : accountFields.filter(item => item.field === 'maxBuckets')" :key="field">
          {{ label }} limit<input v-model.number="limits[field]" type="number" min="-1" max="2147483647" step="1" :disabled="busy" placeholder="Provider default" />
        </label>
      </div>
      <template v-if="!editing && kind === 'user' && !managed">
        <RgwIdentityPicker v-if="!owningAccount" :connection="connection" kind="account" label="Owning account (optional)" :disabled="busy"
          @select="target => { if (target.kind === 'account') owningAccount = target.id }" />
        <div v-else class="settings-row">
          <span>Owning account · {{ owningAccount }}</span>
          <button type="button" :disabled="busy" @click="owningAccount = undefined">Clear account</button>
        </div>
        <label v-if="owningAccount" class="check-label"><input v-model="root" type="checkbox" :disabled="busy" /> Create as account root</label>
      </template>
      <div class="modal-actions">
        <button type="button" :disabled="busy" @click="emit('close')">Cancel</button>
        <button class="primary" :disabled="invalid">{{ busy ? 'Saving…' : editing ? 'Save changes' : `Create ${kind}` }}</button>
      </div>
    </form>
  </Modal>
</template>
